/**
 * @param {unknown} valueData
 */
function markdownCellCreate(valueData) {
    //Escaping table separators and line breaks in generated public documentation.
    return String(valueData ?? '').replaceAll('|', '\\|').replaceAll(/\r?\n/g, ' ');

}

/**
 * @param {{appName: string, appVersion: string, routes: readonly Readonly<Record<string, unknown>>[], plugins?: readonly Readonly<Record<string, unknown>>[], operations?: readonly Readonly<Record<string, unknown>>[]}} documentationData
 */
export function layerDocumentationGenerate(documentationData) {
    const documentLines = [
        `# ${markdownCellCreate(documentationData.appName)} — Layer application`,
        '',
        `Version: \`${markdownCellCreate(documentationData.appVersion)}\`.`,
        '',
        '## Routes',
        '',
        '| Path | Render | Layout | Auth | Offline | Permissions | Preload |',
        '| --- | --- | --- | --- | --- | --- | --- |'
    ];

    //Recording stable route contracts without compiled matcher internals.
    for (const routeData of documentationData.routes) {
        documentLines.push(`| ${markdownCellCreate(routeData.path)} | ${markdownCellCreate(routeData.render)} | ${markdownCellCreate(routeData.layout ?? 'none')} | ${markdownCellCreate(routeData.auth)} | ${markdownCellCreate(routeData.offline)} | ${markdownCellCreate(/** @type {readonly unknown[]} */ (routeData.permissions ?? []).join(', '))} | ${markdownCellCreate(/** @type {readonly unknown[]} */ (routeData.preload ?? []).join(', '))} |`);

    }

    documentLines.push('', '## Operations', '', '| Name | Type | Auth | Permissions |', '| --- | --- | --- | --- |');

    for (const operationData of documentationData.operations ?? []) {
        documentLines.push(`| ${markdownCellCreate(operationData.name)} | ${markdownCellCreate(operationData.type)} | ${markdownCellCreate(operationData.auth)} | ${markdownCellCreate(/** @type {readonly unknown[]} */ (operationData.permissions ?? []).join(', '))} |`);

    }

    documentLines.push('', '## Trusted plugins', '', '| Name | Version | Engine | Capabilities |', '| --- | --- | --- | --- |');

    for (const pluginData of documentationData.plugins ?? []) {
        documentLines.push(`| ${markdownCellCreate(pluginData.name)} | ${markdownCellCreate(pluginData.version)} | ${markdownCellCreate(pluginData.engine)} | ${markdownCellCreate(/** @type {readonly unknown[]} */ (pluginData.capabilities ?? []).join(', '))} |`);

    }

    documentLines.push('', 'Generated by `@solcorp/layer-cli`. Sensitive runtime values are not included.', '');

    return documentLines.join('\n');

}
