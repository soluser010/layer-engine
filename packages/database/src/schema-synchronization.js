import {createHash} from 'node:crypto';
import {schemaMigrationLockAcquire} from './schema-lock.js';
import {LayerDatabaseError} from './database-error.js';
import {layerDatabaseSchemaDefinitionCheck} from './schema-definition.js';
import {
    layerSqlIdentifierQuote,
    layerSystemSchemaRead,
    layerSystemTableReferenceCreate
} from './system-schema.js';

const columnTypeSqlMap = /** @type {Readonly<Record<string, string>>} */ (Object.freeze({
    boolean: 'boolean',
    integer: 'bigint',
    json: 'jsonb',
    number: 'double precision',
    string: 'text',
    timestamp: 'timestamp with time zone',
    uuid: 'uuid'
}));

/**
 * @typedef {object} LayerSchemaReader
 * @property {'embedded' | 'postgres' | undefined} [kind]
 * @property {string} [systemSchema]
 * @property {(queryData: {text: string, values: readonly unknown[]}) => Promise<{rows: Record<string, unknown>[], rowCount: number | null}>} query
 * @typedef {LayerSchemaReader & {transaction: <ResultData>(handlerData: (transactionClientData: LayerSchemaReader) => Promise<ResultData>) => Promise<ResultData>}} LayerSchemaDatabase
 */

/**
 * @param {string} codeData
 * @param {string} messageData
 * @returns {never}
 */
function schemaErrorThrow( codeData, messageData ){
    //Passing a stable synchronization failure without database contents
    throw new LayerDatabaseError( codeData, messageData );

}

/**
 * @param {unknown} valueData
 * @returns {string}
 */
function sqlLiteralCreate( valueData ){
    //Creating explicit SQL literals only from normalized declarative defaults
    if ( valueData === null ){
        //CallBack THE STRING
        return String( 'NULL' );

    }

    if ( typeof valueData === 'boolean' ){
        if ( valueData === true ){
            //CallBack THE STRING
            return String( 'TRUE' );

        }

        //CallBack THE STRING
        return String( 'FALSE' );

    }

    if ( typeof valueData === 'number' ){
        if ( Number.isFinite( valueData ) === false ){
            return schemaErrorThrow( 'DATABASE_SCHEMA_INVALID', 'Schema default is not finite.' );

        }

        //CallBack THE STRING
        return String( valueData );

    }

    if ( typeof valueData === 'string' ){
        //CallBack THE STRING
        return `'${String( valueData ).replaceAll( "'", "''" )}'`;

    }

    const jsonSourceData = JSON.stringify( valueData );

    if ( jsonSourceData === undefined ){
        return schemaErrorThrow( 'DATABASE_SCHEMA_INVALID', 'Schema JSON default is invalid.' );

    }

    //CallBack THE STRING
    return `'${String( jsonSourceData ).replaceAll( "'", "''" )}'::jsonb`;

}

/**
 * @param {Readonly<Record<string, unknown>>} columnData
 * @param {boolean} [includePrimaryStatusData]
 */
function columnSqlCreate( columnData, includePrimaryStatusData = false ){
    const sqlTypeData = columnTypeSqlMap[String( columnData.type )];

    if ( sqlTypeData === undefined ){
        return schemaErrorThrow( 'DATABASE_SCHEMA_INVALID', 'Schema column type is invalid.' );

    }

    let columnSqlData = `${layerSqlIdentifierQuote( String( columnData.databaseName ) )} ${String( sqlTypeData )}`;

    //Adding identity generation only for declared integer identity columns
    if ( columnData.generated === 'identity' ){
        columnSqlData += ' GENERATED BY DEFAULT AS IDENTITY';

    }

    if ( columnData.defaultPresent === true ){
        columnSqlData += ` DEFAULT ${sqlLiteralCreate( columnData.default )}`;

    }

    if ( columnData.nullable !== true ){
        columnSqlData += ' NOT NULL';

    }

    if ( includePrimaryStatusData === true ){
        columnSqlData += ' PRIMARY KEY';

    }

    //CallBack THE STRING
    return columnSqlData;

}

/**
 * @param {Readonly<Record<string, unknown>>} tableData
 */
function expectedColumnsCreate( tableData ){
    const expectedColumnsData = [];

    //Copying every developer column into the physical schema plan
    for ( const columnData of /** @type {readonly Readonly<Record<string, unknown>>[]} */ (tableData.columns) ){
        expectedColumnsData.push( columnData );

    }

    //Adding one engine-owned ownership column according to the declared scope
    if ( tableData.scope === 'tenant' ){
        expectedColumnsData.push( Object.freeze({
            name: 'sysTenantId',
            databaseName: 'sys_tenant_id',
            type: 'string',
            nullable: false,
            generated: null,
            defaultPresent: false,
            default: undefined,
            ownership: true
        }) );

    } else if ( tableData.scope === 'user' ){
        expectedColumnsData.push( Object.freeze({
            name: 'sysUserId',
            databaseName: 'sys_user_id',
            type: 'string',
            nullable: false,
            generated: null,
            defaultPresent: false,
            default: undefined,
            ownership: true
        }) );

    }

    //CallBack THE OBJECT
    return expectedColumnsData;

}

/**
 * @param {string} systemSchemaData
 * @param {Readonly<Record<string, unknown>>} tableData
 */
function tableCreateSql( systemSchemaData, tableData ){
    const columnSqlData = [];

    //Creating a complete safe table statement from trusted schema metadata
    for ( const columnData of expectedColumnsCreate( tableData ) ){
        const primaryStatusData = String( columnData.name ) === String( tableData.primaryKey );
        columnSqlData.push( columnSqlCreate( columnData, primaryStatusData ) );

    }

    //CallBack THE STRING
    return `CREATE TABLE ${layerSqlIdentifierQuote( systemSchemaData )}.${layerSqlIdentifierQuote( String( tableData.name ) )} (${columnSqlData.join( ', ' )})`;

}

/**
 * @param {Readonly<Record<string, unknown>>} columnData
 */
function informationSchemaTypeCreate( columnData ){
    const sqlTypeData = columnTypeSqlMap[String( columnData.type )];

    if ( sqlTypeData === undefined ){
        return schemaErrorThrow( 'DATABASE_SCHEMA_INVALID', 'Schema column type is invalid.' );

    }

    //CallBack THE STRING
    return String( sqlTypeData );

}

/**
 * @param {object} planOptionsData
 * @param {LayerSchemaReader} planOptionsData.database
 * @param {unknown} planOptionsData.schema
 */
export async function layerDatabaseSchemaPlan( planOptionsData ){
    //Checking external PostgreSQL and schema ownership before introspection
    if (
        typeof planOptionsData?.database?.query !== 'function' ||
        planOptionsData.database.kind !== 'postgres' ||
        layerDatabaseSchemaDefinitionCheck( planOptionsData.schema ) === false
    ){
        return schemaErrorThrow( 'APPLICATION_DATABASE_REQUIRED', 'Schema planning requires external PostgreSQL.' );

    }

    const schemaData = planOptionsData.schema;
    const systemSchemaData = layerSystemSchemaRead( planOptionsData.database );
    const existingColumnsResultData = await planOptionsData.database.query({
        text: `
            SELECT table_name, column_name, data_type, is_nullable, column_default, is_identity
            FROM information_schema.columns
            WHERE table_schema = $1
                AND table_name NOT LIKE 'sys\\_%' ESCAPE '\\'
            ORDER BY table_name ASC, ordinal_position ASC
        `,
        values: [systemSchemaData]
    });
    const existingTablesData = new Map();

    //Indexing the current physical application schema without system tables
    for ( const columnRowData of existingColumnsResultData.rows ){
        const tableNameData = String( columnRowData.table_name );
        const tableColumnsData = existingTablesData.get( tableNameData ) ?? new Map();

        tableColumnsData.set( String( columnRowData.column_name ), columnRowData );
        existingTablesData.set( tableNameData, tableColumnsData );

    }

    const additiveStatementsData = [];
    const changesData = [];
    const declaredTableNamesData = new Set();
    let blockingStatusData = false;

    //Comparing every declared table with the current physical schema
    for ( const tableData of schemaData.tables ){
        declaredTableNamesData.add( tableData.name );

        const existingTableColumnsData = existingTablesData.get( tableData.name );

        if ( existingTableColumnsData === undefined ){
            additiveStatementsData.push( tableCreateSql( systemSchemaData, tableData ) );
            changesData.push( Object.freeze({
                type: 'table-add',
                table: tableData.name,
                blocking: false
            }) );

            continue;

        }

        const expectedColumnsData = expectedColumnsCreate( tableData );
        const expectedColumnNamesData = new Set();

        //Comparing declared columns and planning only safe additions automatically
        for ( const columnData of expectedColumnsData ){
            expectedColumnNamesData.add( columnData.databaseName );

            const existingColumnData = existingTableColumnsData.get( columnData.databaseName );

            if ( existingColumnData === undefined ){
                const safeAdditionStatusData = (
                    columnData.nullable === true ||
                    columnData.defaultPresent === true ||
                    columnData.generated === 'identity'
                );

                if ( safeAdditionStatusData === true ){
                    additiveStatementsData.push(
                        `ALTER TABLE ${layerSqlIdentifierQuote( systemSchemaData )}.${layerSqlIdentifierQuote( String( tableData.name ) )} ADD COLUMN ${columnSqlCreate( columnData )}`
                    );

                } else {
                    blockingStatusData = true;

                }

                changesData.push( Object.freeze({
                    type: 'column-add',
                    table: tableData.name,
                    column: columnData.databaseName,
                    blocking: safeAdditionStatusData === false
                }) );

                continue;

            }

            const expectedTypeData = informationSchemaTypeCreate( columnData );
            const actualTypeData = String( existingColumnData.data_type );
            const expectedNullableStatusData = columnData.nullable === true;
            const actualNullableStatusData = String( existingColumnData.is_nullable ) === String( 'YES' );

            //Blocking incompatible types or nullability tightening until operator approval
            if (
                String( expectedTypeData ) !== String( actualTypeData ) ||
                (expectedNullableStatusData === false && actualNullableStatusData === true)
            ){
                blockingStatusData = true;
                changesData.push( Object.freeze({
                    type: 'column-incompatible',
                    table: tableData.name,
                    column: columnData.databaseName,
                    expectedType: expectedTypeData,
                    actualType: actualTypeData,
                    expectedNullable: expectedNullableStatusData,
                    actualNullable: actualNullableStatusData,
                    blocking: true
                }) );

            }

        }

        //Recording removed declarative columns without deleting physical data automatically
        for ( const existingColumnNameData of existingTableColumnsData.keys() ){
            if ( expectedColumnNamesData.has( existingColumnNameData ) === false ){
                changesData.push( Object.freeze({
                    type: 'column-remove',
                    table: tableData.name,
                    column: existingColumnNameData,
                    blocking: false
                }) );

            }

        }

    }

    //Recording removed declarative tables while leaving their physical data untouched
    for ( const existingTableNameData of existingTablesData.keys() ){
        if ( declaredTableNamesData.has( existingTableNameData ) === false ){
            changesData.push( Object.freeze({
                type: 'table-remove',
                table: existingTableNameData,
                blocking: false
            }) );

        }

    }

    const checksumSourceData = JSON.stringify({
        schema: systemSchemaData,
        additiveStatements: additiveStatementsData,
        changes: changesData
    });
    const checksumData = createHash( 'sha256' ).update( checksumSourceData, 'utf8' ).digest( 'hex' );

    //CallBack THE OBJECT
    return Object.freeze({
        checksum: checksumData,
        schema: systemSchemaData,
        additiveStatements: Object.freeze( additiveStatementsData ),
        changes: Object.freeze( changesData ),
        blocking: blockingStatusData
    });

}

/**
 * @param {LayerSchemaReader} databaseData
 * @param {Awaited<ReturnType<typeof layerDatabaseSchemaPlan>>} planData
 */
async function schemaPlanRecord( databaseData, planData ){
    //Skipping durable plan storage when no manual or destructive change exists
    if ( Number( planData.changes.length ) === Number( planData.additiveStatements.length ) ){
        const manualChangeStatusData = planData.changes.some(function manualChangeFind( changeData ){
            //Finding changes without a matching automatic additive statement
            return changeData.type === 'column-remove' || changeData.type === 'table-remove' || changeData.blocking === true;

        });

        if ( manualChangeStatusData === false ){
            return;

        }

    }

    const schemaChangesTableData = layerSystemTableReferenceCreate( databaseData, 'sys_schema_changes' );
    let changeTypeData = String( 'destructive' );

    //Classifying blocking plans separately for operator diagnostics
    if ( planData.blocking === true ){
        changeTypeData = String( 'incompatible' );

    }

    //Recording a checksum-addressed operator plan without executing destructive DDL
    await databaseData.query({
        text: `
            INSERT INTO ${String( schemaChangesTableData )} (checksum, status, change_type, plan)
            VALUES ($1, 'pending', $2, $3::jsonb)
            ON CONFLICT (checksum) DO NOTHING
        `,
        values: [
            planData.checksum,
            changeTypeData,
            JSON.stringify({
                schema: planData.schema,
                changes: planData.changes
            })
        ]
    });

}

/**
 * @param {object} synchronizeOptionsData
 * @param {LayerSchemaDatabase} synchronizeOptionsData.database
 * @param {unknown} synchronizeOptionsData.schema
 */
export async function layerDatabaseSchemaSynchronize( synchronizeOptionsData ){
    //Keeping the catalog snapshot, additive DDL and pending plan on one locked connection
    const planData = await synchronizeOptionsData.database.transaction(async function( transactionData ){
        const databaseData = {...transactionData, kind: synchronizeOptionsData.database.kind,
            systemSchema: layerSystemSchemaRead( synchronizeOptionsData.database )};
        await schemaMigrationLockAcquire( databaseData, databaseData.systemSchema, databaseData.kind );
        const currentPlanData = await layerDatabaseSchemaPlan({database: databaseData, schema: synchronizeOptionsData.schema});

        //Persisting incompatible plans without partially changing the schema they describe
        if ( currentPlanData.blocking === true ){
            await schemaPlanRecord( databaseData, currentPlanData );
            return currentPlanData;

        }

        for ( const statementData of currentPlanData.additiveStatements ){
            //Applying only the plan read after the app-wide lock was acquired
            await databaseData.query({text: statementData, values: []});

        }

        //Recording remaining removals against the catalog after successful additive work
        const remainingPlanData = await layerDatabaseSchemaPlan({database: databaseData, schema: synchronizeOptionsData.schema});
        await schemaPlanRecord( databaseData, remainingPlanData );

        //CallBack THE OBJECT
        return currentPlanData;

    });

    //Reporting readiness failure after the pending approval has committed successfully
    if ( planData.blocking === true ){
        return schemaErrorThrow( 'DATABASE_SCHEMA_APPROVAL_REQUIRED',
            `Database schema change requires approval: ${planData.checksum}.` );

    }

    //CallBack THE OBJECT
    return planData;

}

/**
 * @param {object} applyOptionsData
 * @param {LayerSchemaDatabase} applyOptionsData.database
 * @param {unknown} applyOptionsData.schema
 * @param {string} applyOptionsData.checksum
 * @param {boolean} applyOptionsData.confirmDataLoss
 */
export async function layerDatabaseSchemaApply( applyOptionsData ){
    if ( applyOptionsData?.confirmDataLoss !== true ){
        return schemaErrorThrow( 'DATABASE_SCHEMA_CONFIRMATION_REQUIRED', 'Schema apply requires explicit data-loss confirmation.' );

    }

    if ( typeof applyOptionsData.checksum !== 'string' || /^[0-9a-f]{64}$/.test( applyOptionsData.checksum ) === false ){
        return schemaErrorThrow( 'DATABASE_SCHEMA_CHECKSUM_INVALID', 'Schema apply checksum is invalid.' );

    }

    return applyOptionsData.database.transaction(async function( transactionData ){
        //Revalidating the approved checksum only after the same app lock excludes other workers
        const databaseData = {...transactionData, kind: applyOptionsData.database.kind,
            systemSchema: layerSystemSchemaRead( applyOptionsData.database )};
        await schemaMigrationLockAcquire( databaseData, databaseData.systemSchema, databaseData.kind );
        const planData = await layerDatabaseSchemaPlan({
            database: databaseData,
            schema: applyOptionsData.schema
        });

        if ( String( planData.checksum ) !== String( applyOptionsData.checksum ) ){
            return schemaErrorThrow( 'DATABASE_SCHEMA_CHECKSUM_MISMATCH', 'Schema changed after the approved plan was created.' );

        }

        const schemaData = /** @type {{tables: readonly Readonly<Record<string, any>>[]}} */ (applyOptionsData.schema);
        const destructiveStatementsData = /** @type {string[]} */ ([]);

        //Translating only checksum-approved removals and compatible PostgreSQL conversions
        for ( const changeData of planData.changes ){
            if ( changeData.type === 'table-remove' ){
                destructiveStatementsData.push(
                    `DROP TABLE ${layerSqlIdentifierQuote( planData.schema )}.${layerSqlIdentifierQuote( String( changeData.table ) )}`
                );

                continue;

            }

            if ( changeData.type === 'column-remove' ){
                destructiveStatementsData.push(
                    `ALTER TABLE ${layerSqlIdentifierQuote( planData.schema )}.${layerSqlIdentifierQuote( String( changeData.table ) )} DROP COLUMN ${layerSqlIdentifierQuote( String( changeData.column ) )}`
                );

                continue;

            }

            if ( changeData.type === 'column-add' && changeData.blocking === true ){
                return schemaErrorThrow(
                    'DATABASE_SCHEMA_MANUAL_REQUIRED',
                    'A required column without a safe default needs an application data migration.'
                );

            }

            if ( changeData.type !== 'column-incompatible' ){
                continue;

            }

            const incompatibleChangeData = /** @type {Readonly<Record<string, any>>} */ (changeData);

            const tableData = schemaData.tables.find(function schemaApplyTableFind( /** @type {Readonly<Record<string, any>>} */ currentTableData ){
                //Resolving the approved table against the current application schema
                return String( currentTableData.name ) === String( changeData.table );

            });
            const columnData = tableData?.columns.find(function schemaApplyColumnFind( /** @type {Readonly<Record<string, any>>} */ currentColumnData ){
                //Resolving the approved column before constructing its bounded DDL
                return String( currentColumnData.databaseName ) === String( changeData.column );

            });

            if ( tableData === undefined || columnData === undefined ){
                return schemaErrorThrow( 'DATABASE_SCHEMA_INVALID', 'Approved schema target is unavailable.' );

            }

            const tableReferenceData = `${layerSqlIdentifierQuote( planData.schema )}.${layerSqlIdentifierQuote( tableData.name )}`;
            const columnReferenceData = layerSqlIdentifierQuote( columnData.databaseName );
            const expectedTypeData = informationSchemaTypeCreate( columnData );

            if ( String( incompatibleChangeData.actualType ) !== String( expectedTypeData ) ){
                destructiveStatementsData.push(
                    `ALTER TABLE ${String( tableReferenceData )} ALTER COLUMN ${String( columnReferenceData )} TYPE ${String( expectedTypeData )} USING ${String( columnReferenceData )}::${String( expectedTypeData )}`
                );

            }

            if ( columnData.nullable === false && incompatibleChangeData.actualNullable === true ){
                destructiveStatementsData.push(
                    `ALTER TABLE ${String( tableReferenceData )} ALTER COLUMN ${String( columnReferenceData )} SET NOT NULL`
                );

            }

        }


        for ( const statementData of [...planData.additiveStatements, ...destructiveStatementsData] ){
            await databaseData.query({
                text: statementData,
                values: []
            });

        }

        const schemaChangesTableData = layerSystemTableReferenceCreate(
            databaseData,
            'sys_schema_changes'
        );

        await databaseData.query({
            text: `
                UPDATE ${String( schemaChangesTableData )}
                SET status = 'applied', applied_at = now()
                WHERE checksum = $1
            `,
            values: [planData.checksum]
        });


        //CallBack THE OBJECT
        return Object.freeze({
            checksum: planData.checksum,
            statements: Number( planData.additiveStatements.length ) + Number( destructiveStatementsData.length )
        });

    });

}
