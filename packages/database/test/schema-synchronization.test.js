import assert from 'node:assert/strict';
import test from 'node:test';
import {
    LayerDatabaseError,
    layerDatabaseSchemaApply,
    layerDatabaseSchemaDefine,
    layerDatabaseSchemaPlan,
    layerDatabaseSchemaSynchronize,
    layerTableDefine
} from '../src/index.js';


//Function for creating a schema with additive and ownership metadata
const synchronizationSchemaCreate = function(){
    //Creating one tenant table with generated, required, defaulted, and nullable columns
    const messageTableData = layerTableDefine({
        name: 'messages',
        scope: 'tenant',
        primaryKey: 'id',
        columns: {
            id: {
                type: 'integer',
                generated: 'identity'
            },
            text: {
                type: 'string'
            },
            status: {
                type: 'string',
                default: 'new'
            },
            note: {
                type: 'string',
                nullable: true
            }
        }
    });

    //CallBack THE OBJECT
    return layerDatabaseSchemaDefine([
        messageTableData
    ]);

};

/**
 * @param {Record<string, unknown>[]} informationRowsData
 */
function schemaDatabaseFakeCreate( informationRowsData ){
    const queryCallsData = /** @type {{text: string, values: readonly unknown[]}[]} */ ([]);
    const transactionCallsData = /** @type {{text: string, values: readonly unknown[]}[]} */ ([]);
    const databaseData = {
        kind: /** @type {'postgres'} */ ('postgres'),
        systemSchema: 'layer_schema_test',

        async query( /** @type {{text: string, values: readonly unknown[]}} */ queryData ){
            //Recording lock, plan, and introspection calls separately from DDL
            queryCallsData.push( queryData );

            if ( queryData.text.includes( 'information_schema.columns' ) === true ){
                return {
                    rows: informationRowsData,
                    rowCount: informationRowsData.length
                };

            }

            return {
                rows: [],
                rowCount: 1
            };

        },

        /**
         * @template ResultData
         * @param {(transactionClientData: any) => Promise<ResultData>} transactionHandlerData
         * @returns {Promise<ResultData>}
         */
        async transaction( transactionHandlerData ){
            //Providing a dedicated DDL transaction recorder
            return transactionHandlerData({
                kind: 'postgres',
                systemSchema: 'layer_schema_test',
                async query( /** @type {{text: string, values: readonly unknown[]}} */ queryData ){
                    //Recording each additive DDL statement in execution order
                    transactionCallsData.push( queryData );

                    //Using the same catalog snapshot for transaction and non-transaction reads
                    return databaseData.query( queryData );

                }
            });

        }
    };

    //CallBack THE OBJECT
    return {
        database: databaseData,
        queryCalls: queryCallsData,
        transactionCalls: transactionCallsData
    };

}

test('schema synchronization creates a new scoped table under advisory lock', async function(){
    const fakeData = schemaDatabaseFakeCreate( [] );
    const schemaData = synchronizationSchemaCreate();
    const planData = await layerDatabaseSchemaPlan({
        database: fakeData.database,
        schema: schemaData
    });

    assert.equal( planData.blocking, false );
    assert.equal( planData.changes.length, 1 );
    assert.equal( planData.changes[0]?.type, 'table-add' );
    assert.equal( planData.additiveStatements.length, 1 );
    assert.match( planData.additiveStatements[0] ?? '', /CREATE TABLE "layer_schema_test"\."messages"/ );
    assert.match( planData.additiveStatements[0] ?? '', /"sys_tenant_id" text NOT NULL/ );
    assert.match( planData.additiveStatements[0] ?? '', /GENERATED BY DEFAULT AS IDENTITY/ );

    const synchronizedPlanData = await layerDatabaseSchemaSynchronize({
        database: fakeData.database,
        schema: schemaData
    });

    assert.equal( synchronizedPlanData.checksum, planData.checksum );
    assert.equal( fakeData.queryCalls.some(function advisoryLockFind( queryData ){
        //Finding the primary advisory lock before additive DDL
        return queryData.text === 'SELECT pg_advisory_xact_lock($1::bigint)';

    }), true );
    assert.equal( fakeData.queryCalls.some(function advisoryUnlockFind( queryData ){
        //Finding the primary advisory unlock after additive DDL
        return queryData.text === 'SELECT pg_advisory_unlock($1)';

    }), false );
    assert.equal( fakeData.transactionCalls[0]?.text, 'SELECT pg_advisory_xact_lock($1::bigint)' );
    assert.equal( fakeData.transactionCalls[2]?.text, planData.additiveStatements[0] );

});

test('schema synchronization applies safe columns and records removals without deleting data', async function(){
    const fakeData = schemaDatabaseFakeCreate([{
        table_name: 'messages',
        column_name: 'id',
        data_type: 'bigint',
        is_nullable: 'NO',
        column_default: null,
        is_identity: 'YES'
    }, {
        table_name: 'messages',
        column_name: 'text',
        data_type: 'text',
        is_nullable: 'NO',
        column_default: null,
        is_identity: 'NO'
    }, {
        table_name: 'messages',
        column_name: 'sys_tenant_id',
        data_type: 'text',
        is_nullable: 'NO',
        column_default: null,
        is_identity: 'NO'
    }, {
        table_name: 'messages',
        column_name: 'legacy_field',
        data_type: 'text',
        is_nullable: 'YES',
        column_default: null,
        is_identity: 'NO'
    }]);
    const schemaData = synchronizationSchemaCreate();
    const planData = await layerDatabaseSchemaSynchronize({
        database: fakeData.database,
        schema: schemaData
    });

    assert.equal( planData.blocking, false );
    assert.equal( planData.additiveStatements.length, 2 );
    assert.equal( planData.additiveStatements.some(function statusColumnFind( statementData ){
        //Finding the safe non-null column backed by its literal default
        return statementData.includes( '"status" text DEFAULT \'new\' NOT NULL' );

    }), true );
    assert.equal( planData.additiveStatements.some(function noteColumnFind( statementData ){
        //Finding the safe nullable column addition
        return statementData.includes( '"note" text' );

    }), true );
    assert.equal( planData.changes.some(function legacyRemovalFind( changeData ){
        //Checking removal is planned but does not block readiness
        return changeData.type === 'column-remove' && changeData.blocking === false;

    }), true );
    assert.equal( fakeData.transactionCalls.some(function destructiveDdlFind( queryData ){
        //Checking automatic synchronization never drops physical data
        return queryData.text.includes( 'DROP' );

    }), false );
    assert.equal( fakeData.queryCalls.some(function schemaPlanRecordFind( queryData ){
        //Finding the durable checksum plan in the system table
        return queryData.text.includes( '"sys_schema_changes"' );

    }), true );

});

test('schema synchronization blocks incompatible changes after recording checksum plan', async function(){
    const fakeData = schemaDatabaseFakeCreate([{
        table_name: 'messages',
        column_name: 'id',
        data_type: 'bigint',
        is_nullable: 'NO',
        column_default: null,
        is_identity: 'YES'
    }, {
        table_name: 'messages',
        column_name: 'text',
        data_type: 'integer',
        is_nullable: 'NO',
        column_default: null,
        is_identity: 'NO'
    }, {
        table_name: 'messages',
        column_name: 'sys_tenant_id',
        data_type: 'text',
        is_nullable: 'NO',
        column_default: null,
        is_identity: 'NO'
    }]);
    const schemaData = synchronizationSchemaCreate();
    const planData = await layerDatabaseSchemaPlan({
        database: fakeData.database,
        schema: schemaData
    });

    assert.equal( planData.blocking, true );
    assert.match( planData.checksum, /^[0-9a-f]{64}$/ );
    assert.equal( planData.changes.some(function incompatibleColumnFind( changeData ){
        //Finding the incompatible physical type without leaking row data
        return changeData.type === 'column-incompatible' && changeData.column === 'text';

    }), true );

    await assert.rejects(function incompatibleSchemaSynchronize(){
        //Applying only safe additions before returning the operator approval requirement
        return layerDatabaseSchemaSynchronize({
            database: fakeData.database,
            schema: schemaData
        });

    }, function approvalRequiredErrorCheck( errorData ){
        //Checking the stable readiness-blocking error code
        return errorData instanceof LayerDatabaseError && errorData.code === 'DATABASE_SCHEMA_APPROVAL_REQUIRED';

    });
    assert.equal( fakeData.queryCalls.some(function incompatiblePlanRecordFind( queryData ){
        //Checking the incompatible plan was recorded before startup was blocked
        return queryData.text.includes( '"sys_schema_changes"' ) && queryData.values[1] === 'incompatible';

    }), true );

});

test('schema plan checksum is deterministic for identical physical metadata', async function(){
    const firstFakeData = schemaDatabaseFakeCreate( [] );
    const secondFakeData = schemaDatabaseFakeCreate( [] );
    const schemaData = synchronizationSchemaCreate();
    const firstPlanData = await layerDatabaseSchemaPlan({
        database: firstFakeData.database,
        schema: schemaData
    });
    const secondPlanData = await layerDatabaseSchemaPlan({
        database: secondFakeData.database,
        schema: schemaData
    });

    assert.equal( firstPlanData.checksum, secondPlanData.checksum );
    assert.deepEqual( firstPlanData.additiveStatements, secondPlanData.additiveStatements );

});

test('schema apply requires checksum confirmation and executes approved removal', async function(){
    const fakeData = schemaDatabaseFakeCreate([{
        table_name: 'messages',
        column_name: 'id',
        data_type: 'bigint',
        is_nullable: 'NO',
        column_default: null,
        is_identity: 'YES'
    }, {
        table_name: 'messages',
        column_name: 'text',
        data_type: 'text',
        is_nullable: 'NO',
        column_default: null,
        is_identity: 'NO'
    }, {
        table_name: 'messages',
        column_name: 'sys_tenant_id',
        data_type: 'text',
        is_nullable: 'NO',
        column_default: null,
        is_identity: 'NO'
    }, {
        table_name: 'messages',
        column_name: 'legacy_field',
        data_type: 'text',
        is_nullable: 'YES',
        column_default: null,
        is_identity: 'NO'
    }]);
    const schemaData = synchronizationSchemaCreate();
    const planData = await layerDatabaseSchemaPlan({
        database: fakeData.database,
        schema: schemaData
    });

    await assert.rejects(
        function schemaApplyWithoutConfirmation(){
            return layerDatabaseSchemaApply({
                database: fakeData.database,
                schema: schemaData,
                checksum: planData.checksum,
                confirmDataLoss: false
            });

        },
        function confirmationErrorCheck( errorData ){
            return errorData instanceof LayerDatabaseError && errorData.code === 'DATABASE_SCHEMA_CONFIRMATION_REQUIRED';

        }
    );

    const applyResultData = await layerDatabaseSchemaApply({
        database: fakeData.database,
        schema: schemaData,
        checksum: planData.checksum,
        confirmDataLoss: true
    });

    assert.equal( applyResultData.checksum, planData.checksum );
    assert.equal( fakeData.transactionCalls.some(function removedColumnDropFind( queryData ){
        return queryData.text.includes( 'DROP COLUMN "legacy_field"' );

    }), true );
    assert.equal( fakeData.transactionCalls.some(function schemaPlanAppliedFind( queryData ){
        return queryData.text.includes( "SET status = 'applied'" );

    }), true );

    await assert.rejects(
        function staleChecksumApply(){
            return layerDatabaseSchemaApply({
                database: fakeData.database,
                schema: schemaData,
                checksum: '0'.repeat( 64 ),
                confirmDataLoss: true
            });

        },
        function checksumMismatchCheck( errorData ){
            return errorData instanceof LayerDatabaseError && errorData.code === 'DATABASE_SCHEMA_CHECKSUM_MISMATCH';

        }
    );

});
